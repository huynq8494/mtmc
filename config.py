import numpy as np
from configs.cameras import CAMERAS  # generated by parse_camera_config.py from configs/camera_properties.txt

# Video / intrinsics, all taken from the parsed camera config (must be identical for every camera).
_c0 = CAMERAS[min(CAMERAS)]
for _c in CAMERAS.values():
    assert _c["resolution"] == _c0["resolution"] and abs(_c["focal_px"] - _c0["focal_px"]) < 1e-6, \
        f"{_c['name']}: intrinsics differ from {_c0['name']}; per-camera intrinsics are not supported"
W, H = _c0["resolution"]
HFOV = _c0["hfov_deg"]
F = _c0["focal_px"]                        # focal length in pixels (override with --hfov)
MAX_RANGE = 80.0                           # ignore ground hits farther than this (m)

# Walkable ground = bounding box of all camera positions
_p = np.array([c["position"] for c in CAMERAS.values()])
XMIN, YMIN = _p[:, :2].min(0)
XMAX, YMAX = _p[:, :2].max(0)

PEOPLE = 10        # max number of tracks
FUSE_D = 0.8       # cross-camera fusion distance (m), grows with range
GATE = 1.5         # tracker association gate (m)
CONFIRM = 3        # frames before a track is shown (or seen by 2+ cameras at once)
MAX_MISS_S = 3.0   # delete a track after this many seconds without detections


def inside(xy, margin=0.0):
    xy = np.asarray(xy).reshape(-1, 2)
    return ((xy[:, 0] >= XMIN - margin) & (xy[:, 0] <= XMAX + margin) &
            (xy[:, 1] >= YMIN - margin) & (xy[:, 1] <= YMAX + margin))


def clamp(xy):
    return np.array([np.clip(xy[0], XMIN, XMAX), np.clip(xy[1], YMIN, YMAX)])
